export function getAvailableSocialInteractions(actor, target, rel) {
  return SOCIAL_INTERACTIONS.filter((it) => {
    if (it.actorOnly && !it.actorOnly.includes(actor.id)) return false;
    if (it.targetOnly && !it.targetOnly.includes(target.id)) return false;
    if (it.pairOnly) {
      const ok = it.pairOnly.includes(actor.id) && it.pairOnly.includes(target.id);
      if (!ok) return false;
    }
    if (it.requiresNeighborNotMovedIn) {
      if (!target.isNeighbor || target.playable) return false;
    }
    return true;
  }).map((it) => {
    if (it.triggersMoveIn) {
      const unlocked = rel.friendship >= 65 || rel.bond >= 60;
      return {
        ...it,
        locked: !unlocked,
        lockHint: unlocked ? '条件达成！' : `需友谊≥65 或 羁绊≥60`,
      };
    }
    return it;
  });
}
